// Embeds the wasm build as base64 so the package is one plain ES module that works in Node,
// browsers, workers and bundlers without any loader or fetch configuration.
import { readFileSync, writeFileSync } from "node:fs";

const wasm = readFileSync(new URL("../web/igcz.wasm", import.meta.url));
writeFileSync(
  new URL("./igcz-wasm.js", import.meta.url),
  `// Generated by build.js from web/igcz.wasm. Do not edit.\nexport default "${wasm.toString("base64")}";\n`,
);
console.log(`igcz-wasm.js: ${wasm.length} bytes of wasm`);
